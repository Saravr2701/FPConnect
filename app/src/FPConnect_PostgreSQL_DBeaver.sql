CREATE SCHEMA IF NOT EXISTS fpconnect;
SET search_path TO fpconnect, public;

DO $$ BEGIN
    CREATE TYPE tipo_cuenta_enum AS ENUM ('ESTUDIANTE', 'EMPRESA', 'CENTRO_EDUCATIVO');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
    CREATE TYPE estudios_enum AS ENUM ('DAM', 'DAW', 'ASIR', 'SMR', 'ADE', 'TCAE');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
    CREATE TYPE estado_oferta_enum AS ENUM ('ACTIVA', 'CERRADA');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
    CREATE TYPE estado_solicitud_enum AS ENUM ('ENVIADA', 'EN_REVISION', 'RESUELTA');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
    CREATE TYPE resultado_solicitud_enum AS ENUM ('PENDIENTE', 'ACEPTADA', 'RECHAZADA');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
    CREATE TYPE estado_practica_enum AS ENUM ('PENDIENTE', 'EN_CURSO', 'FINALIZADA', 'CANCELADA');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
    CREATE TYPE estado_actividad_enum AS ENUM ('PENDIENTE', 'EN_CURSO', 'COMPLETADA');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    contrasena_hash VARCHAR(255) NOT NULL,
    tipo_cuenta tipo_cuenta_enum NOT NULL,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_usuario_email ON usuario (LOWER(email));

CREATE TABLE IF NOT EXISTS centro_educativo (
    id_usuario BIGINT PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    ciudad VARCHAR(100) NOT NULL,
    pais VARCHAR(100) NOT NULL,
    CONSTRAINT fk_centro_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS empresa (
    id_usuario BIGINT PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    calle VARCHAR(150) NOT NULL,
    numero_calle VARCHAR(30) NOT NULL,
    ciudad VARCHAR(100) NOT NULL,
    pais VARCHAR(100) NOT NULL,
    telefono VARCHAR(30),
    CONSTRAINT fk_empresa_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS estudiante (
    id_usuario BIGINT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellido1 VARCHAR(100) NOT NULL,
    apellido2 VARCHAR(100) NOT NULL,
    ciudad VARCHAR(100) NOT NULL,
    pais VARCHAR(100) NOT NULL,
    id_usuario_centro BIGINT NOT NULL,
    estudios estudios_enum NOT NULL,
    descripcion TEXT,
    curriculum_url TEXT,
    CONSTRAINT fk_estudiante_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_estudiante_centro FOREIGN KEY (id_usuario_centro)
        REFERENCES centro_educativo (id_usuario) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS centro_estudio (
    id_usuario_centro BIGINT NOT NULL,
    estudio estudios_enum NOT NULL,
    PRIMARY KEY (id_usuario_centro, estudio),
    CONSTRAINT fk_centro_estudio_centro FOREIGN KEY (id_usuario_centro)
        REFERENCES centro_educativo (id_usuario) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS habilidad (
    id_habilidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS estudiante_habilidad (
    id_usuario_estudiante BIGINT NOT NULL,
    id_habilidad BIGINT NOT NULL,
    PRIMARY KEY (id_usuario_estudiante, id_habilidad),
    CONSTRAINT fk_estudiante_habilidad_estudiante FOREIGN KEY (id_usuario_estudiante)
        REFERENCES estudiante (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_estudiante_habilidad_habilidad FOREIGN KEY (id_habilidad)
        REFERENCES habilidad (id_habilidad) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS oferta (
    id_oferta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_empresa BIGINT NOT NULL,
    puesto VARCHAR(150) NOT NULL,
    area VARCHAR(120) NOT NULL,
    descripcion TEXT NOT NULL,
    numero_plazas INTEGER NOT NULL CHECK (numero_plazas > 0),
    requisitos TEXT,
    ubicacion VARCHAR(200) NOT NULL,
    fecha_publicacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado estado_oferta_enum NOT NULL DEFAULT 'ACTIVA',
    estudios estudios_enum NOT NULL,
    CONSTRAINT fk_oferta_empresa FOREIGN KEY (id_usuario_empresa)
        REFERENCES empresa (id_usuario) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS solicitud (
    id_solicitud BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_estudiante BIGINT NOT NULL,
    id_oferta BIGINT NOT NULL,
    fecha_solicitud TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado_actual estado_solicitud_enum NOT NULL DEFAULT 'ENVIADA',
    resultado resultado_solicitud_enum NOT NULL DEFAULT 'PENDIENTE',
    CONSTRAINT fk_solicitud_estudiante FOREIGN KEY (id_usuario_estudiante)
        REFERENCES estudiante (id_usuario) ON DELETE RESTRICT,
    CONSTRAINT fk_solicitud_oferta FOREIGN KEY (id_oferta)
        REFERENCES oferta (id_oferta) ON DELETE RESTRICT,
    CONSTRAINT uq_solicitud_estudiante_oferta UNIQUE (id_usuario_estudiante, id_oferta),
    CONSTRAINT ck_solicitud_estado_resultado CHECK (
        (estado_actual IN ('ENVIADA', 'EN_REVISION') AND resultado = 'PENDIENTE')
        OR
        (estado_actual = 'RESUELTA' AND resultado IN ('ACEPTADA', 'RECHAZADA'))
    )
);

CREATE TABLE IF NOT EXISTS historial_solicitud (
    id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud BIGINT NOT NULL,
    estado estado_solicitud_enum NOT NULL,
    fecha_cambio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observaciones TEXT,
    CONSTRAINT fk_historial_solicitud FOREIGN KEY (id_solicitud)
        REFERENCES solicitud (id_solicitud) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS practica (
    id_practica BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud BIGINT NOT NULL UNIQUE,
    fecha_inicio DATE,
    fecha_fin DATE,
    estado estado_practica_enum NOT NULL DEFAULT 'PENDIENTE',
    progreso NUMERIC(5,2) NOT NULL DEFAULT 0,
    CONSTRAINT fk_practica_solicitud FOREIGN KEY (id_solicitud)
        REFERENCES solicitud (id_solicitud) ON DELETE RESTRICT,
    CONSTRAINT ck_practica_progreso CHECK (progreso >= 0 AND progreso <= 100),
    CONSTRAINT ck_practica_fechas CHECK (
        fecha_fin IS NULL OR fecha_inicio IS NULL OR fecha_fin >= fecha_inicio
    )
);

CREATE TABLE IF NOT EXISTS actividad_seguimiento (
    id_actividad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_practica BIGINT NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    descripcion TEXT,
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado estado_actividad_enum NOT NULL DEFAULT 'PENDIENTE',
    CONSTRAINT fk_actividad_practica FOREIGN KEY (id_practica)
        REFERENCES practica (id_practica) ON DELETE CASCADE
);

CREATE OR REPLACE FUNCTION validar_tipo_cuenta_perfil()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    tipo_esperado tipo_cuenta_enum;
    tipo_guardado tipo_cuenta_enum;
BEGIN
    IF TG_TABLE_NAME = 'estudiante' THEN
        tipo_esperado := 'ESTUDIANTE';
    ELSIF TG_TABLE_NAME = 'empresa' THEN
        tipo_esperado := 'EMPRESA';
    ELSIF TG_TABLE_NAME = 'centro_educativo' THEN
        tipo_esperado := 'CENTRO_EDUCATIVO';
    END IF;

    SELECT tipo_cuenta INTO tipo_guardado
    FROM usuario
    WHERE id_usuario = NEW.id_usuario;

    IF tipo_guardado IS NULL THEN
        RAISE EXCEPTION 'No existe el usuario %', NEW.id_usuario;
    END IF;

    IF tipo_guardado <> tipo_esperado THEN
        RAISE EXCEPTION 'El tipo de cuenta es %, pero se intenta crear un perfil %',
            tipo_guardado, tipo_esperado;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_tipo_estudiante ON estudiante;
CREATE TRIGGER trg_validar_tipo_estudiante
BEFORE INSERT OR UPDATE OF id_usuario ON estudiante
FOR EACH ROW EXECUTE FUNCTION validar_tipo_cuenta_perfil();

