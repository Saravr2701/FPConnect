CREATE OR REPLACE FUNCTION registrar_historial_solicitud()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    texto_observaciones TEXT;
BEGIN
    IF TG_OP = 'UPDATE'
       AND OLD.estado_actual IS NOT DISTINCT FROM NEW.estado_actual
       AND OLD.resultado IS NOT DISTINCT FROM NEW.resultado THEN
        RETURN NEW;
    END IF;

    IF TG_OP = 'INSERT' THEN
        texto_observaciones := 'Solicitud creada';
    ELSIF OLD.estado_actual IS DISTINCT FROM NEW.estado_actual THEN
        texto_observaciones := 'Estado cambiado de ' || OLD.estado_actual ||
                               ' a ' || NEW.estado_actual;
    ELSE
        texto_observaciones := 'Resultado actualizado a ' || NEW.resultado;
    END IF;

    IF NEW.estado_actual = 'RESUELTA' THEN
        texto_observaciones := texto_observaciones || '. Resultado: ' || NEW.resultado;
    END IF;

    INSERT INTO historial_solicitud (id_solicitud, estado, observaciones)
    VALUES (NEW.id_solicitud, NEW.estado_actual, texto_observaciones);

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_01_historial_solicitud ON solicitud;
CREATE TRIGGER trg_01_historial_solicitud
AFTER INSERT OR UPDATE OF estado_actual, resultado ON solicitud
FOR EACH ROW EXECUTE FUNCTION registrar_historial_solicitud();

CREATE OR REPLACE FUNCTION crear_practica_si_aceptada()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.estado_actual = 'RESUELTA' AND NEW.resultado = 'ACEPTADA' THEN
        INSERT INTO practica (id_solicitud)
        VALUES (NEW.id_solicitud)
        ON CONFLICT (id_solicitud) DO NOTHING;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_02_crear_practica ON solicitud;
CREATE TRIGGER trg_02_crear_practica
AFTER INSERT OR UPDATE OF estado_actual, resultado ON solicitud
FOR EACH ROW EXECUTE FUNCTION crear_practica_si_aceptada();

